#!/usr/bin/env python3
"""Write contracts/halmos/REPORT.md from the logs of `make halmos` (one log per Halmos run, plus the Z3 lemma log).

Each Halmos result line (`[PASS]`, `[FAIL]`, `[TIMEOUT]`, `[ERROR]`) becomes a row with its paths, time and bounds.
Expected outcomes are declared below; the script exits 1 (and still writes the report) when a property that must
PASS does not, or when a reachability canary that must FAIL passes (then the property it guards was checked on
states that never occurred). TIMEOUT is reported as such and never counted as proved.

usage: report.py OUT_MD HALMOS_VERSION LEMMA_LOG RUN_LOG [RUN_LOG ...]   (RUN_LOG name: <label>.log)
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

LINE = re.compile(
    r"\[(PASS|FAIL|TIMEOUT|ERROR)\]\s+(\w+)\(([^)]*)\)\s+\(paths: (\d+), time: ([\d.]+)s.*?, bounds: \[(.*)\]\)\s*$",
    re.M,
)
ANSI = re.compile(r"\x1b\[[0-9;]*m")

# expected outcome per test name prefix
EXPECT = {
    "invariant_canary_": "FAIL",  # reachability canaries: a counterexample shows the state is reached
    "check_canary_": "FAIL",
    "check_rounding": "TIMEOUT",  # 256-bit bit-vector rounding lemma: does not finish; proved by the Z3 lemma
}


def expected(name: str) -> str:
    for prefix, outcome in EXPECT.items():
        if name.startswith(prefix):
            return outcome
    return "PASS"


def main(argv: list[str]) -> int:
    if len(argv) < 5:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    out_md, version, lemma_log, run_logs = Path(argv[1]), argv[2], Path(argv[3]), [Path(p) for p in argv[4:]]
    rows, bad = [], []
    for log in run_logs:
        label = log.stem
        text = ANSI.sub("", log.read_text())
        found = LINE.findall(text)
        markers = len(re.findall(r"^\[(?:PASS|FAIL|TIMEOUT|ERROR)\]", text, re.M))
        if not found:
            bad.append(f"{label}: no result lines (did Halmos run?)")
        if markers != len(found):
            bad.append(f"{label}: {markers} results in the log but {len(found)} parsed")
        for status, name, _args, paths, secs, bounds in found:
            want = expected(name)
            ok = status == want
            rows.append((label, name, status, want, int(paths), float(secs), bounds, ok))
            if not ok:
                bad.append(f"{label}: {name} is {status}, expected {want}")
    # The core the Halmos runs executed is the pinned v1 core: same deployedBytecode hashes as `make core-bytecode`.
    here = Path(__file__).resolve().parent.parent
    pinned = dict(
        reversed(line.split())
        for line in (here / "deployments" / "core_bytecode.sha256").read_text().splitlines()
        if line.strip()
    )
    core_same = []
    for name in ("MethaneCovenant", "KeyRegistry"):
        art = json.loads((here / "out" / "halmos" / f"{name}.sol" / f"{name}.json").read_text())
        same = hashlib.sha256(art["deployedBytecode"]["object"].encode()).hexdigest() == pinned.get(name)
        core_same.append(f"{name} {'unchanged' if same else 'CHANGED'}")
        if not same:
            bad.append(f"{name} in the Halmos build differs from the pinned v1 core bytecode")
    lemma = lemma_log.read_text()
    lemma_ok = lemma.count("proved") == 2 and "tight " in lemma and "FAIL" not in lemma and "UNKNOWN" not in lemma
    if not lemma_ok:
        bad.append("rounding lemma (Z3): not proved")

    md = ["# Halmos report", ""]
    md.append(f"Generated by `make halmos` (Halmos {version}, solver yices, the run's bounds in each label). Do not edit")
    md.append("by hand. `PASS` on a `check_` function: no input violates its assertions (paths explored as listed);")
    md.append("on an `invariant_` function: no sequence of target calls up to the label's depth violates it. `FAIL` on a")
    md.append("`canary` is the expected outcome: Halmos found a sequence reaching that state, so the invariants of the")
    md.append("same run were checked on states that contain it. `TIMEOUT` is not a proof. Each run's flags are in the")
    md.append("`halmos` target of `mk/lane-a.mk`: loops unrolled to 32 (pool-installments) or 4 (the others); any-order")
    md.append("depth 2 (pool) and 1 (core); 65-byte signatures in the core runs; 60 s per assertion for rounding-256-bit.")
    md.append("")
    md.append("Core bytecode in the Halmos build against the pinned v1 hashes (`deployments/core_bytecode.sha256`): "
              + ", ".join(core_same) + ".")
    md.append("")
    md.append("| Run | Property | Result | Expected | Paths | Time (s) | Bounds |")
    md.append("|---|---|---|---|---|---|---|")
    for label, name, status, want, paths, secs, bounds, ok in rows:
        mark = "" if ok else " **unexpected**"
        md.append(f"| {label} | `{name}` | {status}{mark} | {want} | {paths} | {secs:.2f} | {bounds or '-'} |")
    md.append("")
    md.append("## Rounding lemma (Z3, unbounded integers)")
    md.append("")
    md.append("Run by `make halmos` with the Python that ships with Halmos (`halmos/rounding_lemma.py`):")
    md.append("")
    md.append("```")
    md.extend(line.rstrip() for line in lemma.splitlines() if line.strip())
    md.append("```")
    md.append("")
    status = "all outcomes as expected" if not bad else f"{len(bad)} unexpected outcome(s)"
    md.append(f"Summary: {len(rows)} Halmos results, {status}.")
    for b in bad:
        md.append(f"- {b}")
    out_md.write_text("\n".join(md) + "\n")
    print(f"halmos: {len(rows)} results, {status}; {out_md} written")
    for b in bad:
        print(f"   unexpected: {b}", file=sys.stderr)
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
