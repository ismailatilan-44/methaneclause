#!/usr/bin/env python3
"""Write contracts/slither.md from a Slither JSON run and the committed triage (make slither).

Every finding must match a triage entry (check + Contract.function, or '*' for every location of that check with
an exact `count`), and every entry must still match a finding; otherwise this exits 1 and writes nothing. The report's counts come from the
JSON, not from hand.

usage: slither_report.py SLITHER_JSON TRIAGE_JSON OUT_MD SLITHER_VERSION
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

CORE = {"MethaneCovenant", "KeyRegistry"}  # byte-identical by rule (make core-bytecode)
IMPACTS = ["High", "Medium", "Low", "Informational", "Optimization"]


def location(r: dict) -> tuple[str, str, str]:
    """(contract, function, 'file#lines') of a finding's first element."""
    e = r["elements"][0]
    tsf = e.get("type_specific_fields", {})
    if e["type"] == "function":
        fn, contract = e["name"], tsf["parent"]["name"]
    else:  # a variable or node: its parent is the function
        parent = tsf["parent"]
        fn = parent["name"]
        contract = parent["type_specific_fields"]["parent"]["name"]
    sm = e["source_mapping"]
    lines = sm.get("lines") or [0]
    where = f"{sm['filename_relative']}#{lines[0]}" + (f"-{lines[-1]}" if len(lines) > 1 else "")
    return contract, fn, where


def main(argv: list[str]) -> int:
    if len(argv) != 5:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    run = json.loads(Path(argv[1]).read_text())
    if not run.get("success"):
        print(f"slither did not complete: {run.get('error')}", file=sys.stderr)
        return 1
    findings = run.get("results", {}).get("detectors", [])
    entries = json.loads(Path(argv[2]).read_text())["entries"]
    used = [0] * len(entries)
    rows = []
    unmatched = []
    for r in findings:
        contract, fn, where = location(r)
        key = f"{contract}.{fn}"
        match = next((i for i, t in enumerate(entries) if t["check"] == r["check"] and t["where"] == key), None)
        if match is None:
            match = next((i for i, t in enumerate(entries) if t["check"] == r["check"] and t["where"] == "*"), None)
        if match is None:
            unmatched.append(f"{r['impact']} {r['check']} {key} ({where})")
            continue
        used[match] += 1
        rows.append((r, contract, fn, where, match))
    stale = [f"{t['check']} {t['where']}" for t, n in zip(entries, used) if n == 0]
    # a wildcard entry pins how many locations it accepts: a new location of that check fails the run
    miscounted = [
        f"{t['check']} *: {n} findings, triage accepts {t.get('count')}"
        for t, n in zip(entries, used)
        if t["where"] == "*" and n != t.get("count")
    ]
    if unmatched or stale or miscounted:
        for m in miscounted:
            print(f"wildcard count changed (review the new locations, then update `count`): {m}", file=sys.stderr)
        for u in unmatched:
            print(f"untriaged finding: {u}", file=sys.stderr)
        for s in stale:
            print(f"triage entry matches no finding (remove it): {s}", file=sys.stderr)
        return 1

    by_impact = collections.Counter(r["impact"] for r, *_ in rows)
    by_verdict = collections.Counter(entries[m]["verdict"] for *_, m in rows)
    in_core = sum(1 for _, c, *_ in rows if c in CORE)
    contracts = sorted({c for _, c, *_ in rows})
    out = []
    out.append("# Slither report")
    out.append("")
    out.append(f"Generated by `make slither` (Slither {argv[4]}, solc 0.8.37, optimizer 200 runs) over `contracts/src`: the")
    out.append("v1 core (`MethaneCovenant`, `KeyRegistry` and their internal libraries), `IncentivePool` with its five linked")
    out.append("libraries, `SuretyBond` and `KeyRegistryV2`; tests, scripts and `lib/` are not compiled into the run. Do not edit")
    out.append("by hand: the triage lives in `contracts/slither.triage.json` and the run fails on any finding it does not")
    out.append("cover. The v1 core is byte-identical by rule (`make core-bytecode`), so its findings are explained, never fixed.")
    out.append("")
    out.append("| Impact | Findings |")
    out.append("|---|---|")
    for imp in IMPACTS:
        out.append(f"| {imp} | {by_impact.get(imp, 0)} |")
    out.append(f"| **Total** | **{len(rows)}** |")
    out.append("")
    verdicts = ", ".join(f"{by_verdict.get(v, 0)} {v}" for v in ("fixed", "false-positive", "accepted"))
    high_medium = sum(1 for r, *_ in rows if r["impact"] in ("High", "Medium"))
    libs = ("PoolVerify", "PoolSetup", "PoolEpisodes", "PoolCorroboration", "PoolInstallments")
    in_libs = sum(1 for _, c, *_ in rows if c in libs)
    out.append(f"Verdicts: {verdicts}.")
    out.append(f"High or Medium findings: {high_medium}, each with a verdict and its reason below; none left open.")
    out.append(f"Findings in the v1 core: {in_core}; in the five pool libraries: {in_libs}.")
    out.append(f"Contracts with findings: {', '.join(contracts)}.")
    out.append("")
    groups: dict[tuple[str, str, int], list] = collections.defaultdict(list)
    for r, contract, fn, where, m in rows:
        groups[(r["impact"], r["check"], m)].append((contract, fn, where, r["confidence"]))
    order = sorted(groups, key=lambda k: (IMPACTS.index(k[0]), k[1], k[2]))
    out.append("## Findings and triage")
    for imp, check, m in order:
        t = entries[m]
        locs = groups[(imp, check, m)]
        scope = f"all {t['count']} locations" if t["where"] == "*" else t["where"]
        out.append("")
        out.append(f"### {imp} · `{check}` · {scope} — {t['verdict']} ({len(locs)})")
        out.append("")
        out.append(t["reason"])
        out.append("")
        for contract, fn, where, conf in sorted(set(locs)):
            core = " (v1 core)" if contract in CORE else ""
            out.append(f"- `{contract}.{fn}` — `{where}`, confidence {conf}{core}")
    Path(argv[3]).write_text("\n".join(out) + "\n")
    print(f"slither: {len(rows)} findings, all triaged ({verdicts}); {argv[3]} written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
